//! Generación de launchers (`.sh`, `.bat`, `.json`, `windows-launcher-v1.ps1`).

use crate::{
    steam::manager::{SteamShortcutManager, WindowsLaunchConfiguration},
    util::{atomic::write_atomic, shell_argument},
};
use base64::{Engine, engine::general_purpose::STANDARD as BASE64};
use emusync_domain::{execution::parse_arguments, library::Emulator};
use std::{
    fs, io,
    path::{Path, PathBuf},
};

const WINDOWS_LAUNCHER_V1_PS1: &str = include_str!("windows-launcher-v1.ps1");

pub(crate) fn invalid_input(
    message: impl Into<Box<dyn std::error::Error + Send + Sync>>,
) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidInput, message)
}

/// Escribe de forma atómica; en Unix, `executable` crea el temporal ya con modo 0o755.
pub(crate) fn write_launcher_file(file: &Path, contents: &str, executable: bool) -> io::Result<()> {
    let mode = if executable { Some(0o755) } else { None };
    write_atomic(file, contents.as_bytes(), mode, |_| Ok(()))
}

/// Plantilla única del `.bat` que delega en PowerShell.
pub(crate) fn windows_batch(encoded: &str) -> String {
    format!(
        "@echo off\r\nsetlocal DisableDelayedExpansion\r\npowershell.exe -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand {encoded}\r\nexit /b %ERRORLEVEL%\r\n"
    )
}

/// Script bash que delega en el launcher `target`.
pub(crate) fn linux_bridge(target: &Path) -> io::Result<String> {
    let target_arg = shell_argument(&target.to_string_lossy(), false).map_err(invalid_input)?;
    Ok(format!("#!/bin/bash\nexec {target_arg} \"$@\"\n"))
}

fn fullscreen_tokens(entry: &Emulator) -> io::Result<Vec<String>> {
    let raw_fs = SteamShortcutManager::resolve_fullscreen_args(entry);
    if raw_fs.trim().is_empty() {
        return Ok(Vec::new());
    }
    parse_arguments(&raw_fs)
        .ok_or_else(|| invalid_input("Fullscreen arguments contain unmatched quotes"))
}

impl SteamShortcutManager {
    pub fn create_wrapper_script(&self, entry: &Emulator) -> io::Result<PathBuf> {
        if self.is_windows() {
            self.create_windows_wrapper_script(entry)
        } else {
            self.create_linux_wrapper_script(entry)
        }
    }

    pub fn create_linux_wrapper_script(&self, entry: &Emulator) -> io::Result<PathBuf> {
        let launcher_dir = self.get_launcher_dir();
        let key = self.launcher_key(&entry.common.name);
        let script_file = launcher_dir.join(format!("launch_{key}.sh"));
        let signal_file = self.get_signal_file(entry);

        let args_part = entry
            .common
            .arguments
            .iter()
            .map(|arg| shell_argument(arg, true).map_err(invalid_input))
            .collect::<io::Result<Vec<_>>>()?
            .join(" ");

        let fs_args_tokens = fullscreen_tokens(entry)?
            .iter()
            .map(|t| shell_argument(t, false).map_err(invalid_input))
            .collect::<io::Result<Vec<_>>>()?
            .join(" ");
        let fs_args_line = format!("FULLSCREEN_ARGS=({fs_args_tokens})");

        let signal_arg =
            shell_argument(&signal_file.to_string_lossy(), false).map_err(invalid_input)?;
        let exe_arg =
            shell_argument(&entry.common.executable_path, false).map_err(invalid_input)?;

        let sanitized_name = entry.common.name.replace(['\r', '\n'], " ");

        let contents = format!(
            "#!/bin/bash\n# Auto-generated by EmuSync — do not edit manually.\n# Launcher for: {sanitized_name}\n\nSIGNAL_FILE={signal_arg}\n\nif [ ! -f \"$SIGNAL_FILE\" ]; then\n    echo \"EmuSync: No ROM path found. Launch a game from EmuSync first.\"\n    exit 1\nfi\n\nROM_PATH=$(cat \"$SIGNAL_FILE\")\n\nif [ ! -e \"$ROM_PATH\" ]; then\n    echo \"EmuSync: ROM file not found: $ROM_PATH\"\n    exit 1\nfi\n\n# Fullscreen/Big Picture flags to bypass Qt windowed GUI\n{fs_args_line}\n\necho \"EmuSync: Launching with: $ROM_PATH\"\nexec {exe_arg} \"${{FULLSCREEN_ARGS[@]}}\" {args_part}\n"
        );

        write_launcher_file(&script_file, &contents, true)?;
        Ok(script_file)
    }

    pub fn create_windows_wrapper_script(&self, entry: &Emulator) -> io::Result<PathBuf> {
        let launcher_dir = self.get_launcher_dir();
        let key = self.launcher_key(&entry.common.name);
        let signal_file = self.get_signal_file(entry);
        let signal_str = signal_file.to_string_lossy().to_string();

        let mut all_args = fullscreen_tokens(entry)?;
        all_args.extend(entry.common.arguments.iter().cloned());

        for arg in [&entry.common.executable_path, &signal_str]
            .into_iter()
            .chain(all_args.iter())
        {
            if arg.contains('\0') {
                return Err(invalid_input(
                    "Launcher paths and arguments cannot contain NUL",
                ));
            }
        }

        fs::create_dir_all(&launcher_dir)?;
        let script_file = launcher_dir.join("windows-launcher-v1.ps1");
        write_launcher_file(&script_file, WINDOWS_LAUNCHER_V1_PS1, false)?;

        let config = WindowsLaunchConfiguration {
            executable: entry.common.executable_path.clone(),
            signal_file: signal_str,
            arguments: all_args,
        };
        let config_json = serde_json::to_string(&config)
            .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e.to_string()))?;
        let config_file = launcher_dir.join(format!("launch_{key}.json"));
        write_launcher_file(&config_file, &config_json, false)?;

        let batch_file = launcher_dir.join(format!("launch_{key}.bat"));
        write_launcher_file(
            &batch_file,
            &windows_batch(&self.encoded_command(&key)),
            false,
        )?;

        Ok(batch_file)
    }

    pub fn encoded_command(&self, key: &str) -> String {
        let launcher_dir = self.get_launcher_dir();
        let script_path = launcher_dir.join("windows-launcher-v1.ps1");
        let config_path = launcher_dir.join(format!("launch_{key}.json"));

        let script_b64 = BASE64.encode(script_path.to_string_lossy().as_bytes());
        let config_b64 = BASE64.encode(config_path.to_string_lossy().as_bytes());

        let command = format!(
            "& ([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('{script_b64}'))) -ConfigPath ([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('{config_b64}')))\nexit $LASTEXITCODE"
        );

        let utf16_bytes: Vec<u8> = command
            .encode_utf16()
            .flat_map(|u| u.to_le_bytes())
            .collect();

        BASE64.encode(&utf16_bytes)
    }
}
